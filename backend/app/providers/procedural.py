"""Procedural (algorithmic) audio: original music and sound effects synthesised
with NumPy. No models, no downloads, no licensing questions, runs on any CPU.
Quality is simpler than AI audio; it is the zero-dependency fallback.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
from scipy.io import wavfile
from scipy.signal import butter, lfilter

from .base import MusicProvider, SfxProvider

SR = 48000


def _bp(x, lo, hi):
    b, a = butter(2, [lo / (SR / 2), min(hi, SR / 2 - 100) / (SR / 2)], btype="band")
    return lfilter(b, a, x)


def _lp(x, f):
    b, a = butter(2, f / (SR / 2), btype="low")
    return lfilter(b, a, x)


def _hp(x, f):
    b, a = butter(2, f / (SR / 2), btype="high")
    return lfilter(b, a, x)


def _reverb(x: np.ndarray, mix: float = 0.3) -> np.ndarray:
    out = np.copy(x)
    for d_ms, g in ((29.7, 0.75), (37.1, 0.72), (41.1, 0.7), (43.7, 0.68)):
        d = int(SR * d_ms / 1000)
        y = np.zeros(len(x) + d * 8)
        y[: len(x)] += x
        for i in range(1, 8):  # cheap multi-tap feedback comb
            y[i * d: i * d + len(x)] += x * (g ** i)
        out += y[: len(x)] * (mix / 4)
    return out


def _write(out: Path, left: np.ndarray, right: np.ndarray, peak: float = 0.8) -> Path:
    st = np.stack([left, right], axis=1)
    m = np.max(np.abs(st)) or 1.0
    st = st / m * peak
    out.parent.mkdir(parents=True, exist_ok=True)
    wavfile.write(str(out), SR, (st * 32767).astype(np.int16))
    return out


def _midi(n: float) -> float:
    return 440.0 * 2 ** ((n - 69) / 12)


PROGRESSIONS = {  # root-position triads as MIDI notes
    "sad": [[57, 60, 64], [53, 57, 60], [48, 52, 55], [55, 59, 62]],       # Am F C G
    "happy": [[48, 52, 55], [55, 59, 62], [57, 60, 64], [53, 57, 60]],     # C G Am F
    "tense": [[50, 53, 57], [46, 50, 53], [45, 49, 52], [50, 53, 57]],     # Dm Bb A Dm
    "calm": [[53, 57, 60], [48, 52, 55], [50, 53, 57], [46, 50, 53]],      # F C Dm Bb
    "epic": [[50, 53, 57], [46, 50, 53], [48, 52, 55], [45, 49, 52]],      # Dm Bb C A
}
MOOD_WORDS = {
    "sad": ["sad", "lost", "lonely", "fear", "scared", "melanch", "cry", "alone", "worried"],
    "happy": ["happy", "joy", "reunion", "reunite", "found", "playful", "cheer", "hope", "warm", "uplift"],
    "tense": ["tense", "danger", "chase", "suspense", "threat", "storm", "hunt", "dark"],
    "epic": ["epic", "heroic", "triumph", "cinematic", "majestic", "grand", "brave"],
    "calm": ["calm", "peace", "gentle", "soft", "dawn", "sleep", "quiet"],
}


def detect_mood(text: str) -> str:
    t = text.lower()
    scores = {m: sum(t.count(w) for w in ws) for m, ws in MOOD_WORDS.items()}
    best = max(scores, key=scores.get)
    return best if scores[best] > 0 else "calm"


class ProceduralMusic(MusicProvider):
    name = "procedural-score"
    limits = "Runs on any CPU in seconds. Simple ambient orchestral-style score (pads, plucks, bass)."
    license = "Original output generated by this engine"
    quality_label = "procedural score"

    def check(self) -> tuple[bool, str]:
        return True, "numpy/scipy synthesis"

    def compose(self, description: str, duration_s: float, out: Path, seed: int = 0) -> Path:
        rng = np.random.default_rng(seed)
        mood = detect_mood(description)
        prog = PROGRESSIONS[mood]
        bpm = {"sad": 64, "happy": 88, "tense": 96, "calm": 60, "epic": 80}[mood]
        bar = 4 * 60 / bpm
        n = int(duration_s * SR)
        t = np.arange(n) / SR
        L, R = np.zeros(n), np.zeros(n)

        bars = int(np.ceil(duration_s / bar)) + 1
        for b in range(bars):
            chord = prog[b % len(prog)]
            s0, s1 = int(b * bar * SR), min(n, int((b + 1) * bar * SR + 0.5 * SR))
            if s0 >= n:
                break
            tt = t[s0:s1] - t[s0]
            env = np.minimum(1, tt / 1.2) * np.minimum(1, (tt[-1] - tt + 1e-3) / 0.8)
            for i, note in enumerate(chord):  # warm detuned pad
                f = _midi(note)
                wave = sum(np.sin(2 * np.pi * f * (1 + d) * tt + rng.uniform(0, 6.28)) for d in (-0.003, 0, 0.004))
                wave += 0.3 * np.sin(2 * np.pi * 2 * f * tt)
                pan = 0.3 + 0.4 * (i / 2)
                L[s0:s1] += wave * env * 0.12 * (1 - pan)
                R[s0:s1] += wave * env * 0.12 * pan
            bass = np.sin(2 * np.pi * _midi(chord[0] - 12) * tt) * env * 0.25
            L[s0:s1] += bass
            R[s0:s1] += bass
            steps = 8 if mood in ("happy", "tense", "epic") else 4  # arpeggio plucks
            for k in range(steps):
                p0 = s0 + int(k * bar / steps * SR)
                if p0 >= n:
                    break
                note = chord[k % 3] + 12 * (1 + (k // 3) % 2)
                ln = min(int(0.9 * SR), n - p0)
                pt = np.arange(ln) / SR
                pl = np.sin(2 * np.pi * _midi(note) * pt) * np.exp(-pt * 5) * 0.09
                pan = rng.uniform(0.2, 0.8)
                L[p0:p0 + ln] += pl * (1 - pan)
                R[p0:p0 + ln] += pl * pan
            if mood in ("tense", "epic"):  # soft timpani pulse
                ln = min(int(0.6 * SR), n - s0)
                pt = np.arange(ln) / SR
                drum = np.sin(2 * np.pi * 55 * pt * (1 - 0.3 * pt)) * np.exp(-pt * 6) * 0.35
                L[s0:s0 + ln] += drum
                R[s0:s0 + ln] += drum

        L, R = _reverb(_lp(L, 6000), 0.35), _reverb(_lp(R, 6000), 0.35)
        fade = np.minimum(1, np.minimum(t / 2.0, (duration_s - t) / 3.0)).clip(0, 1)
        return _write(out, L * fade, R * fade, 0.7)


class ProceduralSfx(SfxProvider):
    name = "procedural-sfx"
    limits = "Runs on any CPU. Synthesised ambience and simple effects (wind, birds, water, rain, rustle, growl, thunder, crickets, fire)."
    license = "Original output generated by this engine"
    quality_label = "procedural SFX"

    def check(self) -> tuple[bool, str]:
        return True, "numpy/scipy synthesis"

    def create(self, cues: list[str], duration_s: float, out: Path, seed: int = 0) -> Path:
        rng = np.random.default_rng(seed)
        n = max(1, int(duration_s * SR))
        t = np.arange(n) / SR
        text = " ".join(cues).lower()
        L, R = np.zeros(n), np.zeros(n)

        def add(sig, pan=0.5, gain=1.0):
            nonlocal L, R
            L += sig * gain * (1 - pan) * 2
            R += sig * gain * pan * 2

        def has(*words):
            return any(w in text for w in words)

        # ambient bed: always a little air so silence never sounds broken
        wind_amt = 0.6 if has("wind", "breeze", "storm", "forest", "jungle", "savanna", "grass") else 0.15
        lfo = 0.6 + 0.4 * np.sin(2 * np.pi * 0.11 * t + rng.uniform(0, 6))
        add(_lp(rng.normal(0, 1, n), 500) * lfo * 0.15, 0.4, wind_amt)
        add(_lp(rng.normal(0, 1, n), 450) * lfo[::-1] * 0.15, 0.6, wind_amt)

        if has("bird", "forest", "jungle", "morning", "dawn", "tree"):
            for _ in range(int(duration_s * 1.5)):
                p0 = int(rng.uniform(0, max(1, n - SR * 0.3)))
                ln = int(SR * rng.uniform(0.05, 0.15))
                pt = np.arange(ln) / SR
                f0 = rng.uniform(2500, 5000)
                chirp = np.sin(2 * np.pi * (f0 + rng.uniform(-1500, 1500) * pt / pt[-1]) * pt) * np.hanning(ln) * 0.15
                sig = np.zeros(n); sig[p0:p0 + ln] = chirp[: n - p0]
                add(sig, rng.uniform(0.1, 0.9))
        if has("water", "river", "stream", "waterfall", "lake", "splash"):
            add(_bp(rng.normal(0, 1, n), 300, 2500) * (0.8 + 0.2 * np.sin(2 * np.pi * 0.7 * t)) * 0.2, 0.5)
        if has("rain"):
            add(_hp(rng.normal(0, 1, n), 2000) * 0.15, 0.5)
            drops = (rng.random(n) > 0.9995).astype(float)
            add(_bp(drops, 1500, 6000) * 4, 0.5)
        if has("rustle", "leaves", "footstep", "walk", "run", "paw", "step", "bush"):
            for k in range(int(duration_s * 2.5)):
                p0 = int((k / 2.5 + rng.uniform(-0.05, 0.05)) * SR)
                if 0 <= p0 < n - 2000:
                    ln = int(SR * rng.uniform(0.06, 0.12))
                    burst = _bp(rng.normal(0, 1, ln), 400, 3000) * np.exp(-np.arange(ln) / (SR * 0.03)) * 0.4
                    sig = np.zeros(n); sig[p0:p0 + ln] = burst[: n - p0]
                    add(sig, 0.5)
        if has("roar", "growl", "rumble", "lion", "tiger", "bear"):
            small = has("cub", "baby", "mew", "squeak", "small")
            ln = min(n, int(SR * (0.8 if small else 1.8)))
            p0 = int(min(n - ln, SR * 0.4)) if n > ln else 0
            pt = np.arange(ln) / SR
            f = (220 if small else 85) * (1 + 0.15 * np.sin(2 * np.pi * 3 * pt)) * (1.1 - 0.3 * pt / pt[-1])
            phase = 2 * np.pi * np.cumsum(f) / SR
            saw = 2 * ((phase / (2 * np.pi)) % 1) - 1
            grit = 0.6 + 0.4 * rng.normal(0, 1, ln)
            voice = _lp(saw * grit, 1800 if small else 900) * np.sin(np.pi * pt / pt[-1]) ** 0.7
            sig = np.zeros(n); sig[p0:p0 + ln] = voice
            add(_reverb(sig, 0.3), 0.5, 0.9)
        if has("thunder", "storm"):
            ln = min(n, int(SR * 3))
            pt = np.arange(ln) / SR
            sig = np.zeros(n); sig[:ln] = _lp(rng.normal(0, 1, ln), 150) * np.exp(-pt * 1.2) * 1.2
            add(sig, 0.5)
        if has("cricket", "night", "insect"):
            pulse = (np.sin(2 * np.pi * 30 * t) > 0.6).astype(float) * (np.sin(2 * np.pi * 0.8 * t) > 0)
            add(np.sin(2 * np.pi * 4500 * t) * pulse * 0.04, 0.7)
        if has("fire", "crackle", "campfire"):
            pops = (rng.random(n) > 0.9993).astype(float)
            add(_hp(pops, 1000) * 3 + _lp(rng.normal(0, 1, n), 300) * 0.08, 0.5)

        fade = np.minimum(1, np.minimum(t / 0.3, (duration_s - t) / 0.3)).clip(0, 1)
        return _write(out, L * fade, R * fade, 0.6)
